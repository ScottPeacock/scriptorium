import Foundation

// Codable mirrors of Grimmory's `org.booklore.app.dto` types.
//
// Grimmory annotates these with @JsonInclude(NON_NULL), so any field can be
// absent from the payload — every property here is optional except the ones
// the server always populates. Verified against grimmory-tools/grimmory@develop.

struct AppPageResponse<T: Decodable & Sendable>: Decodable, Sendable {
    let content: [T]
    let page: Int
    let size: Int
    let totalElements: Int
    let totalPages: Int
    let hasNext: Bool
    let hasPrevious: Bool
}

