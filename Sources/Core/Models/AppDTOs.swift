struct AppBookFile: Decodable, Sendable, Identifiable, Hashable {
    let id: Int64
    let bookId: Int64?
    let fileName: String?
    let bookType: String?
    let fileSizeKb: Int64?
    let fileExtension: String?
    let isBook: Bool?
    let isPrimary: Bool?
    let folderBased: Bool?

    private enum CodingKeys: String, CodingKey {
        case id, bookId, fileName, bookType, fileSizeKb, folderBased
        case fileExtension = "extension"
        case isBook, book
        case isPrimary, primary
    }

    init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(Int64.self, forKey: .id)
        bookId = try c.decodeIfPresent(Int64.self, forKey: .bookId)
        fileName = try c.decodeIfPresent(String.self, forKey: .fileName)
        bookType = try c.decodeIfPresent(String.self, forKey: .bookType)
        fileSizeKb = try c.decodeIfPresent(Int64.self, forKey: .fileSizeKb)
        fileExtension = try c.decodeIfPresent(String.self, forKey: .fileExtension)
        folderBased = try c.decodeIfPresent(Bool.self, forKey: .folderBased)
        isBook = try c.decodeBoolEitherSpelling(.isBook, stripped: .book)
        isPrimary = try c.decodeBoolEitherSpelling(.isPrimary, stripped: .primary)
    }
}

