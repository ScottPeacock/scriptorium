struct AppUserInfo: Decodable, Sendable {
    let isAdmin: Bool
    let canUpload: Bool
    let canDownload: Bool
    let canAccessBookdrop: Bool
    let maxFileUploadSizeMb: Int

    private enum CodingKeys: String, CodingKey {
        case isAdmin, admin
        case canUpload, canDownload, canAccessBookdrop, maxFileUploadSizeMb
    }

    init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        isAdmin = try c.decodeBoolEitherSpelling(.isAdmin, stripped: .admin) ?? false
        canUpload = try c.decodeIfPresent(Bool.self, forKey: .canUpload) ?? false
        canDownload = try c.decodeIfPresent(Bool.self, forKey: .canDownload) ?? false
        canAccessBookdrop = try c.decodeIfPresent(Bool.self, forKey: .canAccessBookdrop) ?? false
        maxFileUploadSizeMb = try c.decodeIfPresent(Int.self, forKey: .maxFileUploadSizeMb) ?? 0
    }
}

